#!/usr/bin/env python3
"""gen_compose - writes docker/compose.yml (agent isolation V1, 2026-10-26).

One dispatcher, two doors and twenty agents, each in its own container:

  dispatcher   the Desk, the record, the routes; on a closed network (no
               internet); holds every agent's line
  desk-door    passes your browser through to the Desk; published on this
               computer's own address only (127.0.0.1:8765)
  alert-door   the only container that can send a text message (the pager);
               the dispatcher asks it over a line, with a fixed menu
  signer       the operator's key and the second factor; on a network of its
               own that the dispatcher is not on; hands over only the public
               key and the signed list of installed files (signer-out, which
               the dispatcher mounts read-only)
  signer-door  passes your browser to the signer's page, on 127.0.0.1:8767 only
  review       the review agent: an observer with no network, the record and
               state mounted read-only, writing only its case files
  agent-01..20 no network at all, read-only, no Linux capabilities, an
               unprivileged user; each sees only its own line

Generated so the twenty agent blocks cannot drift apart; edit this file
and run `python tools/gen_compose.py`. tests_isolation/test_containers.py
checks the committed file matches.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docker", "compose.yml")
AGENTS = [f"{i:02d}" for i in range(1, 21)]

HARDENED = """    image: listingassistants:local
    read_only: true
    user: "10001:10001"
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    tmpfs: ["/tmp:size=64m,mode=1777"]
    restart: unless-stopped"""


def render() -> str:
    out = ["# GENERATED by tools/gen_compose.py - edit that, not this file.",
           "# Agent isolation V1 (owner decisions 2026-10-26). See docs/CONTAINERS.md.",
           "name: listingassistants", "", "services:"]
    out += ["  dispatcher:",
            "    build: {context: .., dockerfile: docker/Dockerfile}",
            HARDENED,
            '    command: ["python", "tools/desk.py"]',
            "    environment:",
            "      LISTINGASSISTANTS_PORTAL: containers",
            "      LISTINGASSISTANTS_PORTAL_DIR: /portal",
            "      LISTINGASSISTANTS_PORTAL_WAIT: \"300\"",
            "      LISTINGASSISTANTS_STATE_DIR: /state",
            "      LISTINGASSISTANTS_IN_CONTAINER: \"1\"",
            "      LISTINGASSISTANTS_ALERT_DOOR: /door/alert.sock",
            "      LISTINGASSISTANTS_SIGNER_URL: http://localhost:8767",
            "      LISTINGASSISTANTS_REVIEWS: /reviews",
            "    networks: [inside]",
            "    mem_limit: 1g",
            "    volumes:",
            "      - state:/state",
            "      - door-alert:/door",
            "      - signer-out:/signer-out:ro",
            "      - reviews:/reviews:ro"]
    out += [f"      - portal-{a}:/portal/{a}" for a in AGENTS]
    out += ["", "  desk-door:", HARDENED,
            '    command: ["python", "tools/desk_door.py", "dispatcher", "8765"]',
            "    networks: [inside, outside]",
            '    ports: ["127.0.0.1:8765:8765"]',
            "    mem_limit: 64m",
            "", "  alert-door:", HARDENED,
            '    command: ["python", "-m", "dispatcher.alert_door", "serve", "/door/alert.sock",'
            ' "/door-config/pager.json"]',
            "    networks: [outside]",
            "    mem_limit: 128m",
            "    volumes:",
            "      - door-alert:/door",
            "      - alert-config:/door-config"]
    out += ["", "  signer:", HARDENED,
            '    command: ["python", "-m", "dispatcher.signer_service", "serve", "--dir", "/signer",'
            ' "--port", "8767"]',
            "    environment:",
            "      LISTINGASSISTANTS_IN_CONTAINER: \"1\"",
            "      LISTINGASSISTANTS_SIGNER_ORIGIN: http://localhost:8767",
            "      LISTINGASSISTANTS_DESK_ORIGIN: http://127.0.0.1:8765",
            "    networks: [signing]",
            "    mem_limit: 256m",
            "    volumes:",
            "      - signer-state:/signer",
            "      - signer-out:/out",
            "", "  signer-door:", HARDENED,
            '    command: ["python", "tools/desk_door.py", "signer", "8767"]',
            "    networks: [signing, outside]",
            '    ports: ["127.0.0.1:8767:8767"]',
            "    mem_limit: 64m"]
    out += ["", "  review:", HARDENED,
            '    command: ["python", "-m", "dispatcher.review_agent", "--state", "/state",'
            ' "--out", "/reviews", "--watch"]',
            "    network_mode: none",
            "    mem_limit: 256m",
            "    volumes:",
            "      - state:/state:ro",
            "      - reviews:/reviews"]
    for a in AGENTS:
        out += ["", f"  agent-{a}:", HARDENED,
                f'    command: ["python", "-m", "dispatcher.portal_agent", "{a}", "/line/portal.sock"]',
                "    environment:",
                '      LISTINGASSISTANTS_CONNECT_WAIT: "0"',
                "    network_mode: none",
                "    mem_limit: 256m",
                "    pids_limit: 64",
                "    volumes:",
                f"      - portal-{a}:/line:ro"]
    out += ["", "networks:", "  inside:", "    internal: true", "  signing:", "    internal: true",
            "  outside: {}",
            "", "volumes:", "  state: {}", "  door-alert: {}", "  alert-config: {}",
            "  signer-state: {}", "  signer-out: {}", "  reviews: {}"]
    out += [f"  portal-{a}: {{}}" for a in AGENTS]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if argv == ["--check"]:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("docker/compose.yml is out of date: run python tools/gen_compose.py")
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
